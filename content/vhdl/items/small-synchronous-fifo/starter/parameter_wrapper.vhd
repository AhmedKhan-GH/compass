library ieee;
use ieee.std_logic_1164.all;
entity fifo_matrix is port(clk,reset:in std_logic;
    v1,r1:in std_logic;
    d1:in std_logic_vector(7 downto 0);
    ir1,ov1:out std_logic;
    q1:out std_logic_vector(7 downto 0);
    v3,r3:in std_logic;
    d3:in std_logic_vector(7 downto 0);
    ir3,ov3:out std_logic;
    q3:out std_logic_vector(7 downto 0);
    v5,r5:in std_logic;
    d5:in std_logic_vector(7 downto 0);
    ir5,ov5:out std_logic;
    q5:out std_logic_vector(7 downto 0));
end;
architecture rtl of fifo_matrix is component top_module is generic(WIDTH:positive;
    DEPTH:positive;
    ADDR_WIDTH:positive);
    port(clk,reset,in_valid:in std_logic;
    in_ready:out std_logic;
    in_data:in std_logic_vector(WIDTH-1 downto 0);
    out_valid:out std_logic;
    out_ready:in std_logic;
    out_data:out std_logic_vector(WIDTH-1 downto 0));
end component;
begin f1:top_module generic map(8,1,1)port map(clk,reset,v1,ir1,d1,ov1,r1,q1);
f3:top_module generic map(8,3,2)port map(clk,reset,v3,ir3,d3,ov3,r3,q3);
f5:top_module generic map(8,5,3)port map(clk,reset,v5,ir5,d5,ov5,r5,q5);
end;
